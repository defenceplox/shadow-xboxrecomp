static unsigned char *load_file(const char *path, size_t *out_size)
{
    FILE *f = fopen(path, "rb");
    if (!f) {
        fprintf(stderr, "cannot open %s\n", path);
        return NULL;
    }
    if (fseek(f, 0, SEEK_END) != 0) {
        fclose(f);
        return NULL;
    }
    long size = ftell(f);
    if (size <= 0) {
        fclose(f);
        return NULL;
    }
    rewind(f);

    unsigned char *data = malloc((size_t)size);
    if (!data) {
        fclose(f);
        return NULL;
    }
    if (fread(data, 1, (size_t)size, f) != (size_t)size) {
        free(data);
        fclose(f);
        return NULL;
    }
    fclose(f);
    *out_size = (size_t)size;
    return data;
}

/* ── Trapped device MMIO ─────────────────────────────────────────────
 *
 * Two devices answer through the x64 decoder:
 *
 *   APU  0xFE800000 (+0x30000)  -- the runtime arms this window PAGE_NOACCESS
 *       when RECOMP_AC97_READY is set; the model lives in src/apu.
 *   NV2A 0xFD000000             -- the toolkit's POSIX nv2a_hook_init is an
 *       empty stub, so the POSIX main has to initialise the model and trap the
 *       register pages itself.
 *
 * Only the register pages are trapped, never the whole 16 MB. The USER window
 * (offset 0x800000, 8 MB) and VRAM are left as ordinary memory: a rep movsd
 * bulk copy into a trapped page lowers to a host memcpy and faults with no way
 * to resume, which is the hazard recorded in xbox_memory_layout.c against the
 * APU's DSP window.
 */
#define MMIO_APU_BASE   0xFE800000u
#define MMIO_APU_SIZE   0x00030000u
#define MMIO_NV2A_BASE  0xFD000000u
#define MMIO_NV2A_SPAN  0x01000000u     /* the 16 MB aperture */

/* The nine blocks the NV2A model actually implements (nv2a_core.c blocktable),
 * as aperture offsets. PGRAPH and PFIFO are two pages each. */
static const uint32_t nv2a_trap_pages[] = {
    0x000000,   /* PMC     */
    0x001000,   /* PBUS    */
    0x002000,   /* PFIFO   */
    0x003000,   /* PFIFO (2nd page) */
    0x008000,   /* PVIDEO  */
    0x009000,   /* PTIMER  */
    0x100000,   /* PFB     */
    0x400000,   /* PGRAPH  */
    0x401000,   /* PGRAPH (2nd page) */
    0x600000,   /* PCRTC   */
    0x680000,   /* PRAMDAC */
};

static int g_apu_trace_left = 30;
static volatile unsigned g_apu_hot[4096];   /* (APU off >> 2) & 0xFFF */

static uint64_t apu_rd_cb(void *dev, uint32_t off, int size)
{
    g_apu_hot[(off >> 2) & 0xFFF]++;
    return mcpx_apu_mmio_read((MCPXAPUState *)dev, off, (unsigned)size);
}

static void apu_wr_cb(void *dev, uint32_t off, uint64_t v, int size)
{
    if (g_apu_trace_left-- > 0)
        fprintf(stderr, "[APUW] 0x%05X <- 0x%08X (size %d)\n",
                off, (unsigned)v, size);
    mcpx_apu_mmio_write((MCPXAPUState *)dev, off, v, (unsigned)size);
}

static int g_force_intr = -1;

static uint64_t nv2a_rd_cb(void *dev, uint32_t off, int size)
{
    uint64_t v = nv2a_mmio_read((NV2AState *)dev, off, (unsigned)size);

    /* Experiment (RECOMP_NV2A_FORCE_INTR=1): report PFIFO/PGRAPH completion in
     * PMC_INTR_0. The title polls that register ~1.1 M times waiting for the
     * GPU to finish, and the model never raises it, so it spins forever. If
     * forcing the bits lets it continue, the missing piece is interrupt
     * delivery from the pushbuffer executor rather than anything in the
     * command stream. */
    if (g_force_intr < 0)
        g_force_intr = getenv("RECOMP_NV2A_FORCE_INTR") ? 1 : 0;
    if (g_force_intr && off == 0x100u)
        v |= 0x100u | 0x1000u;          /* NV_PMC_INTR_0 PFIFO | PGRAPH */
    return v;
}

static void nv2a_wr_cb(void *dev, uint32_t off, uint64_t v, int size)
{
    nv2a_mmio_write((NV2AState *)dev, off, v, (unsigned)size);
}

/* VRAM + RAMIN for the model, then PAGE_NOACCESS on the register pages so the
 * model is asked instead of reading zeros. */
static int nv2a_posix_init(void)
{
    const size_t vram_size  = 64u * 1024u * 1024u;
    const size_t ramin_size = 1u * 1024u * 1024u;
    unsigned char *vram = (unsigned char *)malloc(vram_size + ramin_size);
    unsigned char *base;
    int trapped = 0;

    if (!vram) {
        fprintf(stderr, "[NV2A] cannot allocate %zu MB for VRAM\n",
                (vram_size + ramin_size) >> 20);
        return 0;
    }

    if (!nv2a_init_standalone(vram, (uint32_t)vram_size,
                              vram + vram_size, (uint32_t)ramin_size)) {
        fprintf(stderr, "[NV2A] nv2a_init_standalone failed\n");
        free(vram);
        return 0;
    }

    base = (unsigned char *)xbox_GetMemoryBase();
    if (!base)
        return 0;

    /* The runtime's vblank path twiddles PMC_INTR_0/PCRTC_INTR_0 by writing
     * plain guest memory (InterlockedOr on the aperture). Trapping those pages
     * intercepts that handshake and the guest stops seeing interrupts, so the
     * trap is opt-out for A/B comparison. */
    if (getenv("RECOMP_NV2A_NO_TRAP")) {
        fprintf(stderr, "[NV2A] model up, register pages NOT trapped "
                        "(RECOMP_NV2A_NO_TRAP)\n");
        return 0;
    }

    for (size_t i = 0; i < sizeof(nv2a_trap_pages) / sizeof(nv2a_trap_pages[0]); i++) {
        void *page = base + MMIO_NV2A_BASE + nv2a_trap_pages[i];
        if (mprotect(page, 0x1000, PROT_NONE) == 0)
            trapped++;
        else
            fprintf(stderr, "[NV2A] mprotect failed at aperture +0x%X\n",
                    nv2a_trap_pages[i]);
    }

    fprintf(stderr, "[NV2A] model up: VRAM=%p (%zu MB) RAMIN=%p, "
                    "%d/%zu register pages trapped\n",
            (void *)vram, vram_size >> 20, (void *)(vram + vram_size), trapped,
            sizeof(nv2a_trap_pages) / sizeof(nv2a_trap_pages[0]));
    return trapped > 0;
}

/* Hot-register counter: which trapped NV2A offsets the guest polls. Indexed by
 * (offset >> 2) & 0xFFF, so one slot per dword within a 16 KB window. Cheap
 * enough to sit in the signal path, and it is what names a spin. */
#define NV2A_HOT_SLOTS 4096
static volatile unsigned g_nv2a_hot[NV2A_HOT_SLOTS];

#define MMIO_AC97_BASE  0xFEC00000u
/* 0x3000, not 0x1000.  DirectSound's voice engines pick a per-engine base from
 * a table at 0x3FF128 and kick at (base + 0xFEC0010B): engine 0 -> 0xFEC0011B,
 * engine 1 -> 0xFEC0017B, engine 3 -> 0xFEC0014B, engine 2 -> 0xFEC0210B.  That
 * last one is 0x210B into the window -- outside a 0x1000 page -- so it stayed
 * plain RAM, its kick was never acknowledged, and sub_003EBED6 (DSOUND) spun on
 * it forever (measured: the hottest guest function, ~4k PC samples). */
#define MMIO_AC97_SIZE  0x3000u
#define MMIO_AC97_WORDS (MMIO_AC97_SIZE / 4)

static volatile unsigned g_ac97_hot[MMIO_AC97_WORDS];
static volatile unsigned g_ac97_wot[MMIO_AC97_WORDS];

/* ── PC sampler (opt-in) ──────────────────────────────────────────────
 *
 * gdb cannot attach here (ptrace restricted) and a single backtrace is
 * unreliable at -O3 without DWARF, so when RECOMP_PC_SAMPLE is set an
 * ITIMER_PROF fires every 200 us of CPU time and the handler records the
 * interrupted RIP. After RECOMP_PC_SAMPLE seconds the samples are printed as
 * `PCHIST <hex pc>` lines and the process exits; resolve them with
 * `addr2line -f -e shadow_recomp`. This is how the spin was located.
 */
#define PROF_MAX 16384
struct prof_sample { unsigned tid; uintptr_t pc; };
static struct prof_sample g_prof[PROF_MAX];
static volatile unsigned   g_prof_n;

static void on_prof(int sig, siginfo_t *info, void *uctx)
{
    ucontext_t *uc = (ucontext_t *)uctx;
    unsigned i = g_prof_n;
    (void)sig; (void)info;
    if (i < PROF_MAX) {
        g_prof[i].tid = (unsigned)syscall(SYS_gettid);
        g_prof[i].pc  = (uintptr_t)MMIO_X64_RIP(uc);
        g_prof_n = i + 1;
    }
}

static void on_alarm_dump(int sig)
{
    unsigned n = g_prof_n;
    unsigned long base = 0;
    FILE *m;
    char line[512];
    (void)sig;

    /* The samples are absolute: subtract the executable's load base so they
     * can be resolved with addr2line against the on-disk binary. */
    m = fopen("/proc/self/maps", "r");
    if (m) {
        while (fgets(line, sizeof line, m)) {
            if (strstr(line, "shadow_recomp") && !strstr(line, ".so")) {
                base = strtoul(line, NULL, 16);
                break;
            }
        }
        fclose(m);
    }
    fprintf(stderr, "PCHIST base=%lx count=%u\n", base, n);
    for (unsigned i = 0; i < n; i++)
        fprintf(stderr, "PTID %u %lx\n", g_prof[i].tid,
                (unsigned long)(g_prof[i].pc - base));

    /* Which trapped device offsets the guest hammered. */
    for (unsigned i = 0; i < NV2A_HOT_SLOTS; i++) {
        if (g_nv2a_hot[i])
            fprintf(stderr, "HOT 0x%05X %u\n", i << 2, g_nv2a_hot[i]);
    }
    for (unsigned i = 0; i < MMIO_AC97_WORDS; i++) {
        if (g_ac97_hot[i])
            fprintf(stderr, "AHOT 0x%03X %u\n", i << 2, g_ac97_hot[i]);
    }
    for (unsigned i = 0; i < MMIO_AC97_WORDS; i++) {
        if (g_ac97_wot[i])
            fprintf(stderr, "WHOT 0x%03X %u\n", i << 2, g_ac97_wot[i]);
    }
    for (unsigned i = 0; i < 4096; i++) {
        if (g_apu_hot[i])
            fprintf(stderr, "PHOT 0x%05X %u\n", i << 2, g_apu_hot[i]);
    }
    fflush(stderr);
    _exit(0);
}

static void install_profiler(int seconds)
{
    struct sigaction sa, sa_alrm;
    struct itimerval it;

    memset(&sa, 0, sizeof sa);
    sa.sa_sigaction = on_prof;
    sa.sa_flags = SA_SIGINFO | SA_RESTART;
    sigemptyset(&sa.sa_mask);
    sigaction(SIGPROF, &sa, NULL);

    memset(&sa_alrm, 0, sizeof sa_alrm);
    sa_alrm.sa_handler = on_alarm_dump;
    sigemptyset(&sa_alrm.sa_mask);
    sigaction(SIGALRM, &sa_alrm, NULL);

    it.it_interval.tv_sec = 0;
    it.it_interval.tv_usec = 200;
    it.it_value = it.it_interval;
    setitimer(ITIMER_PROF, &it, NULL);

    alarm((unsigned)seconds);
}

/* AC97 codec window (0xFEC00000). The APU model stops at offset 0x30000, so
 * this page is plain RAM by default. Only two registers are ever touched by
 * this title (0xFEC0012C and 0xFEC0017C), so it is cheap to shadow: the page is
 * copied first (the runtime seeds a codec-ready bit), then trapped, and reads
 * and writes go to the shadow with the first accesses logged. RECOMP_AC97_TRAP
 * enables it; the trace is what says what the guest is waiting for. */
#define MMIO_AC97_BASE_UNUSED 0xFEC00000u

static uint32_t g_ac97_shadow[MMIO_AC97_WORDS];
static int      g_ac97_shadow_ready;
static int      g_ac97_trace_left = 40;

/* The codec is addressed as bytes and words as well as dwords, so a shadow
 * word has to be read and written at the right byte lane. Getting this wrong
 * is invisible for dword accesses and fatal for the byte-sized kick
 * handshake: a byte read at 0x11B that returns the word's low byte never sees
 * the bit the guest is waiting on. */
static uint32_t ac97_rd_word(uint32_t w, uint32_t off, int size)
{
    uint32_t v = g_ac97_shadow[w];
    if (size == 1) return (v >> ((off & 3) * 8)) & 0xFF;
    if (size == 2) return (v >> ((off & 2) * 8)) & 0xFFFF;
    return v;
}

static void ac97_wr_word(uint32_t w, uint32_t off, uint64_t val, int size)
{
    uint32_t cur = g_ac97_shadow[w];
    uint32_t shift = (off & 3) * 8;
    if (size == 1) {
        uint32_t mask = 0xFFu << shift;
        cur = (cur & ~mask) | (((uint32_t)val & 0xFFu) << shift);
    } else if (size == 2) {
        uint32_t s = (off & 2) * 8, mask = 0xFFFFu << s;
        cur = (cur & ~mask) | (((uint32_t)val & 0xFFFFu) << s);
    } else {
        cur = (uint32_t)val;
    }
    g_ac97_shadow[w] = cur;
}

static uint64_t ac97_rd_cb(void *dev, uint32_t off, int size)
{
    uint32_t w = off >> 2, v;
    (void)dev;
    if (w >= MMIO_AC97_WORDS) return 0;
    g_ac97_hot[w]++;
    v = ac97_rd_word(w, off, size);

    /* Kick handshake, read side.
     *
     * The guest may have written the kick before this page was trapped (the
     * shadow copies the page as it stands), and the lifted loop re-tests a
     * cached register, so gcc collapses it to `jmp $`: if the latched value
     * still has bit 1 set, that loop can never exit and no later write ever
     * happens to clear it. Presenting the byte as consumed on read makes the
     * handshake self-closing whichever side arrives first. */
    if (size == 1 && (off == 0x11B || off == 0x17B ||
                      off == 0x14B || off == 0x210B)) {
        uint32_t shift = (off & 3) * 8;
        v &= ~0x02u;
        g_ac97_shadow[w] &= ~(2u << shift);
    }
    if (g_ac97_trace_left-- > 0)
        fprintf(stderr, "[AC97] R 0x%03X = 0x%08X (size %d)\n", off, v, size);
    return v;
}

static void ac97_wr_cb(void *dev, uint32_t off, uint64_t val, int size)
{
    uint32_t w = off >> 2;
    (void)dev;
    if (w >= MMIO_AC97_WORDS) return;
    ac97_wr_word(w, off, val, size);
    g_ac97_wot[w]++;

    /* Voice kick handshake.
     *
     * DirectSound's submit loop (sub_003EBED6 in this title) writes 2 to the
     * byte at 0xFEC0011B, then spins until bit 1 of that same byte reads
     * back 0 -- "the engine consumed the command". On hardware the AC97/GP
     * block clears it; here nothing does, so the loop never exits and audio
     * initialisation never completes. Clearing the bit on write is the same
     * handshake acknowledgement the toolkit already makes for the GP doorbell
     * (apu_dsp.c): it says the command was taken, and computes nothing.
     * 0x17B is the second engine's kick byte and behaves identically. */
    if (off == 0x11B || off == 0x17B || off == 0x14B || off == 0x210B) {
        uint32_t shift = (off & 3) * 8;
        g_ac97_shadow[w] &= ~(2u << shift);
        if (g_ac97_trace_left > 0)
            fprintf(stderr, "[AC97] kick 0x%03X acknowledged (bit1 cleared)\n",
                    off);
    }

    if (g_ac97_trace_left-- > 0)
        fprintf(stderr, "[AC97] W 0x%03X = 0x%08X (size %d)\n",
                off, (uint32_t)val, size);
}

/* Returns 1 if the page was trapped. */
static int ac97_trap_init(void)
{
    unsigned char *base = (unsigned char *)xbox_GetMemoryBase();
    if (!base || g_ac97_shadow_ready)
        return g_ac97_shadow_ready;

    memcpy(g_ac97_shadow, base + MMIO_AC97_BASE, MMIO_AC97_SIZE);

    /* Clear any pending kick bits in the real page as well as the shadow.
     *
     * The page is PROT_NONE while trapped, but the kernel shim re-protects
     * guest ranges (NtAllocateVirtualMemory / MmMapIoSpace) and this aperture
     * is inside one. Once that happens, reads bypass the trap and see the real
     * page: if a kick bit was latched there before the trap went up, the
     * guest's single-read-then-spin loop can never see it clear. The page read
     * 0x1B -- bit 1 set -- which is exactly the spin. Sanitising the real page
     * first makes that path benign. */
    base[MMIO_AC97_BASE + 0x11B] &= (unsigned char)~0x02;
    base[MMIO_AC97_BASE + 0x17B] &= (unsigned char)~0x02;
    g_ac97_shadow[(0x11B >> 2)] &= ~(2u << ((0x11B & 3) * 8));
    g_ac97_shadow[(0x17B >> 2)] &= ~(2u << ((0x17B & 3) * 8));

    if (mprotect(base + MMIO_AC97_BASE, MMIO_AC97_SIZE, PROT_NONE) != 0)
        return 0;
    g_ac97_shadow_ready = 1;
    fprintf(stderr, "[AC97] codec page shadowed + trapped at 0x%08X\n",
            MMIO_AC97_BASE);
    return 1;
}

static int g_trap_trace = -1;   /* -1 = unread; 0 = off */

/* Print the /proc/self/maps line covering a host address. This is the only way
 * to see what protection the kernel actually granted a page, as opposed to
 * what mprotect was asked for. */
static void maps_line_for(const void *addr)
{
    FILE *m = fopen("/proc/self/maps", "r");
    char line[512];
    unsigned long lo, hi;

    if (!m) return;
    while (fgets(line, sizeof line, m)) {
        if (sscanf(line, "%lx-%lx", &lo, &hi) == 2 &&
            (unsigned long)addr >= lo && (unsigned long)addr < hi) {
            fprintf(stderr, "[MAPS] %p -> %s", addr, line);
            break;
        }
    }
    fclose(m);
}

static int mmio_x64_decode_fails;





/* Returns 1 when the fault was a device access that has been serviced. */
static int mmio_trap_service(ucontext_t *uc, const void *fault_addr)
{
    const unsigned char *base = (const unsigned char *)xbox_GetMemoryBase();
    intptr_t delta;
    uint32_t va;

    if (!base || !fault_addr)
        return 0;

    delta = (const unsigned char *)fault_addr - base;
    if (delta < 0 || delta > 0xFFFFFFFFll)
        return 0;
    va = (uint32_t)delta;

    if (va >= 0xFEC00000u && va < 0xFEC01000u) {
        if (g_trap_trace < 0)
            g_trap_trace = getenv("RECOMP_TRAP_TRACE") ? 80 : 0;
        if (g_trap_trace-- > 0)
            fprintf(stderr, "[TRAP] AC97 addr=%p va=0x%08X\n", fault_addr, va);
    }

    if (va >= MMIO_APU_BASE && va < MMIO_APU_BASE + MMIO_APU_SIZE && g_apu_state) {
        if (mmio_emulate_x64(uc, va - MMIO_APU_BASE, g_apu_state,
                             apu_rd_cb, apu_wr_cb))
            return 1;
        if (mmio_x64_decode_fails++ < 20) {
            const uint8_t *p = (const uint8_t *)(uintptr_t)MMIO_X64_RIP(uc);
            /* Not async-signal-safe, but the process is about to die of this
             * fault and the opcode is what says why. */
            fprintf(stderr, "[MMIO] APU decode fail at PC=%p op=%02X%02X "
                            "offset=0x%X\n",
                    (void *)p, p[0], p[1], va - MMIO_APU_BASE);
        }
        return 0;
    }

    if (va >= MMIO_AC97_BASE && va < MMIO_AC97_BASE + MMIO_AC97_SIZE &&
        g_ac97_shadow_ready) {
        if (mmio_emulate_x64(uc, va - MMIO_AC97_BASE, NULL,
                             ac97_rd_cb, ac97_wr_cb))
            return 1;
        if (mmio_x64_decode_fails++ < 20) {
            const uint8_t *p = (const uint8_t *)(uintptr_t)MMIO_X64_RIP(uc);
            fprintf(stderr, "[MMIO] AC97 decode fail at PC=%p "
                            "bytes=%02X %02X %02X %02X offset=0x%X\n",
                    (void *)p, p[0], p[1], p[2], p[3], va - MMIO_AC97_BASE);
        }
        return 0;
    }

    if (va >= MMIO_NV2A_BASE && va < MMIO_NV2A_BASE + MMIO_NV2A_SPAN) {
        NV2AState *nv2a = nv2a_get_state();
        uint32_t off = va - MMIO_NV2A_BASE;

        g_nv2a_hot[(off >> 2) & (NV2A_HOT_SLOTS - 1)]++;

        if (nv2a && mmio_emulate_x64(uc, off, nv2a, nv2a_rd_cb, nv2a_wr_cb))
            return 1;
        if (mmio_x64_decode_fails++ < 20) {
            const uint8_t *p = (const uint8_t *)(uintptr_t)MMIO_X64_RIP(uc);
            fprintf(stderr, "[MMIO] NV2A decode fail at PC=%p "
                            "bytes=%02X %02X %02X %02X %02X %02X %02X %02X "
                            "offset=0x%X%s\n",
                    (void *)p, p[0], p[1], p[2], p[3], p[4], p[5], p[6], p[7],
                    va - MMIO_NV2A_BASE, nv2a ? "" : " (no model)");
        }
        return 0;
    }

    return 0;
}

/* A fault in recompiled code is ordinary native code failing, so the signal
 * tells us the host address and nothing about the guest. What still works is
 * the guest stack: every lifted call pushes its guest return address, so
 * scanning up from esp for values inside the code range names the chain.
 *
 * ponytail: it is a scan, not a walk. FPO frames have no ebp chain, and the
 * scan over-reports addresses left behind by returned-from calls. Naming the
 * guest function is the whole question at a fault, so it is good enough. */
static void on_fatal_signal(int sig, siginfo_t *info, void *uctx)
{
    /* A device-register access is expected and services itself. Only a fault
     * that is not one of those is fatal. */
    if (sig == SIGSEGV && info &&
        mmio_trap_service((ucontext_t *)uctx, info->si_addr))
        return;

    fprintf(stderr, "\n[FAULT] signal %d (%s) at host %p\n",
            sig,
            sig == SIGSEGV ? "SIGSEGV" : sig == SIGBUS  ? "SIGBUS"
                            : sig == SIGILL ? "SIGILL"
                            : sig == SIGFPE ? "SIGFPE"
                                            : "other",
            info ? info->si_addr : NULL);
    fprintf(stderr, "  guest esp = 0x%08X   code range 0x%08X-0x%08X\n",
            g_esp, g_xbox_code_lo, g_xbox_code_hi);

    const unsigned char *base = (const unsigned char *)xbox_GetMemoryBase();
    if (base && g_esp && g_xbox_mem_offset) {
        const uint32_t *sp = (const uint32_t *)(base + g_esp);
        int shown = 0;
        fprintf(stderr, "  guest stack (candidate return addresses):\n");
        for (int i = 0; i < 512 && shown < 24; i++) {
            uint32_t v = sp[i];
            if (v > g_xbox_code_lo && v < g_xbox_code_hi) {
                fprintf(stderr, "    [esp+%-5d] 0x%08X\n", i * 4, v);
                shown++;
            }
        }
        if (!shown)
            fprintf(stderr, "    (none in range -- the stack may be gone)\n");
    }
    fflush(stderr);
    _exit(2);
}

static void install_fault_handlers(void)
{
    /* A separate stack, so a stack overflow can still be reported instead of
     * dying on the stack it just exhausted. A fixed size, because glibc 2.34+
     * defines SIGSTKSZ as sysconf(_SC_SIGSTKSZ), which is not a constant. */
    static char altstack[64 * 1024];
    stack_t ss;
    memset(&ss, 0, sizeof ss);
    ss.ss_sp = altstack;
    ss.ss_size = sizeof altstack;
    sigaltstack(&ss, NULL);

    struct sigaction sa;
    memset(&sa, 0, sizeof sa);
    sa.sa_sigaction = on_fatal_signal;
    sa.sa_flags = SA_SIGINFO | SA_ONSTACK;
    sigemptyset(&sa.sa_mask);
    sigaction(SIGSEGV, &sa, NULL);
    sigaction(SIGBUS, &sa, NULL);
    sigaction(SIGILL, &sa, NULL);
    sigaction(SIGFPE, &sa, NULL);
}

int main(int argc, char **argv)
{
    const char *xbe_path = argc > 1 ? argv[1] : SHADOW_XBE_PATH;
    const char *game_dir = argc > 2 ? argv[2] : SHADOW_GAME_DIR;

    setvbuf(stdout, NULL, _IONBF, 0);
    setvbuf(stderr, NULL, _IONBF, 0);

    printf("=== Shadow the Hedgehog - static recompilation (POSIX host) ===\n");
    printf("XBE:      %s\n", xbe_path);
    printf("game dir: %s\n", game_dir);

    install_fault_handlers();

    /* Optional PC sampler: RECOMP_PC_SAMPLE=<seconds>. Prints a PCHIST
     * histogram of interrupted RIPs and exits; used to find guest spins. */
    if (getenv("RECOMP_PC_SAMPLE"))
        install_profiler(atoi(getenv("RECOMP_PC_SAMPLE")));

    /* Step 1: the XBE, whose section table drives the memory model. */
    size_t xbe_size = 0;
    unsigned char *xbe_data = load_file(xbe_path, &xbe_size);
    if (!xbe_data) {
        fprintf(stderr, "failed to load the XBE\n");
        return 1;
    }
    printf("XBE loaded: %zu bytes\n", xbe_size);

    /* The APU trap window is armed inside MemoryLayoutInit, which reads this
     * once, so it has to be in the environment before that call. Measured as
     * the single biggest win available here: without it the guest faults on
     * its first MCPX register access. */
    if (!getenv("RECOMP_NO_APU"))
        setenv("RECOMP_AC97_READY", "1", 0);

    /* Step 2: map the guest address space (64 MB + mirror views) and place the
     * toolkit region above the image. Everything after this assumes it. */
    if (!xbox_MemoryLayoutInit(xbe_data, xbe_size)) {
        fprintf(stderr, "xbox_MemoryLayoutInit failed -- the required virtual "
                        "address range may be unavailable\n");
        free(xbe_data);
        return 1;
    }
    g_xbox_mem_offset = xbox_GetMemoryOffset();
    printf("guest memory mapped, offset 0x%llX, code 0x%08X-0x%08X\n",
           (unsigned long long)g_xbox_mem_offset,
           g_xbox_code_lo, g_xbox_code_hi);

    /* NV2A: the toolkit's POSIX hook is an empty stub, so this project can
     * supply one. Measured worse than plain RAM for this title (the runtime's
     * vblank path twiddles PMC_INTR_0 by writing guest memory, which a trap
     * intercepts), so it is opt-in: RECOMP_NV2A_MODEL=1. */
    nv2a_hook_init(g_xbox_mem_offset);   /* no-op on POSIX, kept for parity */
    if (getenv("RECOMP_NV2A_MODEL") && !nv2a_posix_init())
        fprintf(stderr, "[BOOT] NV2A model unavailable; GPU registers will "
                        "read as zero\n");

    /* AC97 codec page: shadow + trap. On by default, because DirectSound's
     * voice-kick handshake lives in this page and plain RAM can never
     * acknowledge it. RECOMP_NO_AC97_TRAP turns it off for A/B comparison. */
    if (!getenv("RECOMP_NO_AC97_TRAP") && !ac97_trap_init())
        fprintf(stderr, "[AC97] codec page could not be trapped\n");

    /* Diagnostic: the protection the kernel actually granted the codec page,
     * and the two bases that address translation uses (RECOMP_MAPS_DUMP=1). */
    if (getenv("RECOMP_MAPS_DUMP")) {
        const unsigned char *b = (const unsigned char *)xbox_GetMemoryBase();
        fprintf(stderr, "[MAPS] base=%p offset=%td\n", (const void *)b,
                (ptrdiff_t)g_xbox_mem_offset);
        if (b) {
            maps_line_for(b + MMIO_AC97_BASE);
            maps_line_for(b + MMIO_AC97_BASE + 0x11B);
        }
    }

    /* APU: MemoryLayoutInit only arms the MMIO trap window when
     * RECOMP_AC97_READY is set in the environment; the model is created here,
     * because a trap with no model declines every access and a model nothing
     * traps into never sees a register. */
    if (getenv("RECOMP_AC97_READY")) {
        extern MCPXAPUState *g_apu_state;
        g_apu_state = mcpx_apu_init_standalone((uint8_t *)xbox_GetMemoryBase());
        fprintf(stderr, "[BOOT] emulated APU %s\n",
                g_apu_state ? "up" : "FAILED to initialise");
    }

    /* Step 3: kernel replacement, then path translation for file I/O. */
    xbox_kernel_init();
    xbox_path_init(game_dir, NULL);

    /* Step 4: the kernel bridge -- the thunk table the guest calls ordinals
     * through. Must come after kernel_init. */
    xbox_kernel_bridge_init();

    /* Step 5: the guest stack pointer. XBOX_STACK_TOP follows the image and is
     * set by MemoryLayoutInit. */
    g_esp = XBOX_STACK_TOP;
    printf("esp = 0x%08X (stack base 0x%08X)\n", g_esp, g_xbox_stack_base);

    /* Step 6: flat dispatch table for indirect calls. Optional by design --
     * without it recomp_lookup falls back to a binary search. */
    if (!recomp_dispatch_init())
        fprintf(stderr, "[BOOT] flat dispatch unavailable; indirect calls "
                        "will use the binary search\n");

    xbox_WatchdogStart();

    printf("calling entry point 0x%08X\n", 0x002AFB53u);
    fflush(stdout);
    xbe_entry_point();

    printf("\nentry point returned\n");
    xbox_kernel_shutdown();
    xbox_MemoryLayoutShutdown();
    free(xbe_data);
    return 0;
}
