/**
 * Shadow the Hedgehog - POSIX host entry point
 *
 * The toolkit's templates/new-game/src/main.c is Win32-only (windows.h,
 * dbghelp, WinMain), and the toolkit ships no POSIX equivalent, so this file
 * does the same job on Linux: load the XBE, bring up the guest memory model,
 * kernel shim and bridge, then call the recompiled entry point.
 *
 * Differences from the Win32 template, and why:
 *   - No Vectored Exception Handler / dbghelp. A SIGSEGV/SIGBUS/SIGILL/SIGFPE
 *     handler does the same job here, and the guest call chain is recovered by
 *     scanning the guest stack for return addresses inside the code range --
 *     the FPO frames have no ebp chain to walk either way.
 *   - No MessageBoxA; diagnostics go to stderr.
 *   - The APU bring-up gated on RECOMP_AC97_READY is omitted: it needs a
 *     trapped register window, which is a separate step from getting the
 *     entry point to run.
 *
 * XBE values (from tools.xbe_parser):
 *   Title   Shadow The Hedgehog (SE-134)
 *   Entry   0x002AFB53
 *   XDK     5849
 */

